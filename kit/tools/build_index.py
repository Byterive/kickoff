#!/usr/bin/env python3
"""Generate INDEX.md in every folder that holds markdown files (stdlib only).

Usage: python tools/build_index.py [project_root] [--verbose] [--force]
Reads YAML-ish frontmatter (title, summary, keywords, status) from each .md file and
writes a generated INDEX.md per folder plus a root INDEX.md linking to child indexes.
INDEX.md files are generated: never edit them by hand.

Safety rules (kickoff 1.4.1):
- skip_dirs come from the PROJECT's tools/budgets.json (else .kickoff/budgets.json, else this script's own budgets.json);
  an entry matches a folder name or a path relative to the root (for example "tests/fixtures"). Nothing is written under them.
- A file is only replaced if it is a generated INDEX.md. An existing file that matches the name case-insensitively
  (for example index.md) or has no "GENERATED by tools/build_index.py" marker is left alone and reported.
- The root must be a kickoff project (PROJECT_STATUS.md, or its own tools/build_index.py). --force overrides.
- --verbose lists every file created, changed or skipped.
"""
import json
import os
import re
import sys

args = [a for a in sys.argv[1:] if not a.startswith("--")]
ROOT = os.path.abspath(args[0]) if args else os.getcwd()
VERBOSE, FORCE = "--verbose" in sys.argv, "--force" in sys.argv
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SKIP = {".git", "node_modules", "Library", "Temp", "Logs", "obj", "bin",
                "__pycache__", ".venv", "venv", "vendor", "_inbox"}
FM = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)
MARKER = re.compile(r"GENERATED by (tools/)?build_index")


def budgets_path():
    for p in (os.path.join(ROOT, "tools", "budgets.json"), os.path.join(ROOT, ".kickoff", "budgets.json"),
              os.path.join(HERE, "budgets.json")):
        if os.path.exists(p):
            return p
    return None


def load_skip():
    skip = set(DEFAULT_SKIP)
    path = budgets_path()
    if path:
        with open(path, encoding="utf-8") as f:
            skip |= {s.strip("/").replace("\\", "/") for s in json.load(f).get("skip_dirs", [])}
    return skip


def skipped(skip, cur, name):
    rel = os.path.relpath(os.path.join(cur, name), ROOT).replace(os.sep, "/")
    return name in skip or rel in skip


def parse(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    m = FM.match(text)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip("[]")
    return meta


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def has_md(path, skip):
    for cur, dirnames, files in os.walk(path):
        dirnames[:] = [d for d in dirnames if not skipped(skip, cur, d) and not d.startswith(".")]
        if any(f.endswith(".md") and f != "INDEX.md" for f in files):
            return True
    return False


def main():
    if not FORCE and not (os.path.exists(os.path.join(ROOT, "PROJECT_STATUS.md"))
                          or os.path.exists(os.path.join(ROOT, "tools", "build_index.py"))):
        print(f"build_index: {ROOT} is not a kickoff project (no PROJECT_STATUS.md, no tools/build_index.py). "
              "Run it from the project, or pass --force.", file=sys.stderr)
        return 2
    skip = load_skip()
    created, changed, left, refused, processed = [], [], 0, [], 0
    for cur, dirnames, files in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if not skipped(skip, cur, d) and not d.startswith("."))
        mds = sorted(f for f in files if f.endswith(".md") and f != "INDEX.md")
        children = [d for d in dirnames if os.path.exists(os.path.join(cur, d))]
        rel = os.path.relpath(cur, ROOT)
        is_root = rel == "."
        if not mds and not is_root and not children:
            continue
        rows = []
        for f in mds:
            m = parse(os.path.join(cur, f))
            rows.append((f, m.get("title", f), m.get("summary", "MISSING SUMMARY"),
                         m.get("keywords", ""), m.get("status", "")))
        out = ["# Index: " + ("project root" if is_root else rel.replace(os.sep, "/")),
               "", "<!-- GENERATED by tools/build_index.py. Do not edit. -->", ""]
        if rows:
            out += ["| File | Summary | Keywords | Status |", "|---|---|---|---|"]
            for f, t, s, k, st in rows:
                out.append(f"| [{cell(t)}]({f}) | {cell(s)} | {cell(k)} | {cell(st)} |")
            out.append("")
        subs = [d for d in dirnames if has_md(os.path.join(cur, d), skip)]
        if subs:
            out += ["## Subfolders", ""]
            for d in subs:
                out.append(f"- [{d}/]({d}/INDEX.md)")
            out.append("")
        text = "\n".join(out)
        target = os.path.join(cur, "INDEX.md")
        clash = [n for n in os.listdir(cur) if n.lower() == "index.md" and n != "INDEX.md"]
        existing = None
        if os.path.exists(target) and not clash:
            with open(target, encoding="utf-8", errors="replace") as fh:
                existing = fh.read()
        if clash or (existing is not None and not MARKER.search(existing)):
            refused.append(os.path.join(rel, clash[0] if clash else "INDEX.md").replace(os.sep, "/"))
            continue
        processed += 1
        if existing is None:
            created.append(os.path.join(rel, "INDEX.md").replace(os.sep, "/"))
        elif existing != text:
            changed.append(os.path.join(rel, "INDEX.md").replace(os.sep, "/"))
        else:
            left += 1
            continue
        with open(target, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"build_index: wrote {processed} INDEX.md file(s)")
    if VERBOSE:
        print(f"build_index: skip list from {budgets_path() or 'defaults'}")
        for p in created:
            print(f"  created   {p}")
        for p in changed:
            print(f"  changed   {p}")
        print(f"  unchanged {left}")
    for p in refused:
        print(f"  SKIPPED   {p} (exists and is not a generated INDEX.md; left untouched)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
